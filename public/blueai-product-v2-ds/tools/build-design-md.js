#!/usr/bin/env node
/* BlueAI Product V2 Design System: builds DESIGN.md.
   Reads the catalog (guide/catalog.jsx, plain data run in a vm sandbox), then concatenates every
   design-md/<number>-<id>.md partial in catalog order under its group heading, with a contents list
   on top, and writes DESIGN.md at the system root. Edit the partials, never DESIGN.md.
   Each partial starts with "## <number> <title>", then Status, Why, and per part the ten labels
   Purpose, Anatomy, Variants, Sizes, States, Props, Motion, Accessibility, Responsive, Do / Don't.
   Usage: node tools/build-design-md.js   (no dependencies) */
'use strict';
const fs = require('fs');
const path = require('path');
const vm = require('vm');

const DS = path.resolve(__dirname, '..');

function loadCatalog() {
  const ctx = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(DS, 'guide', 'catalog.jsx'), 'utf8'), ctx, { filename: 'catalog.jsx' });
  if (!ctx.window.V2Catalog) throw new Error('guide/catalog.jsx did not set window.V2Catalog');
  return ctx.window.V2Catalog;
}

// GitHub-style heading anchor.
function slug(text) {
  return text.trim().toLowerCase().replace(/[^\p{L}\p{N} _-]/gu, '').replace(/ /g, '-');
}

function main() {
  const C = loadCatalog();
  const missing = [];
  const blocks = [];
  const contents = [];
  for (const g of C.groups) {
    const list = C.inGroup(g.id);
    if (!list.length) continue;
    contents.push('- **' + g.title + '**');
    blocks.push('# ' + g.title, '');
    for (const s of list) {
      const rel = C.partialFile(s);
      const file = path.join(DS, rel);
      let body;
      if (fs.existsSync(file)) {
        body = fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n').trim();
      } else {
        missing.push(rel);
        body = '## ' + s.number + ' ' + s.title + '\n\n_Not written yet._';
      }
      const first = body.split('\n').find((l) => /^##\s/.test(l)) || ('## ' + s.number + ' ' + s.title);
      const heading = first.replace(/^##\s+/, '');
      contents.push('  - [' + heading + '](#' + slug(heading) + ')');
      blocks.push(body, '');
    }
  }
  const out = [
    '# ' + C.name,
    '',
    'The target design system the PM builds the next iterations of BlueAI Product V2 from. Every part',
    'carries a status: **In V2** (carried as is), **Changed from V2** (V2 today next to the system, with',
    'why), or **New** (why the product needs it). The live guide is `blueai-product-v2-ds/index.html`.',
    '',
    '_Generated by `tools/build-design-md.js` from `design-md/*.md` in catalog order. Edit the partials,',
    'not this file._',
    '',
    '## Contents',
    '',
    ...contents,
    '',
    ...blocks,
  ];
  fs.writeFileSync(path.join(DS, 'DESIGN.md'), out.join('\n').replace(/\n{3,}/g, '\n\n'));
  console.log('DESIGN.md written: ' + C.sections.length + ' sections, ' + (C.sections.length - missing.length) + ' partials found.');
  if (missing.length) {
    console.log('Missing partials (placeholders written): ' + missing.length);
    missing.forEach((m) => console.log('  ' + m));
  }
}

main();
